-- 12. USER_LOGS
CREATE TABLE USER_LOGS (
    ID_LOG INT AUTO_INCREMENT PRIMARY KEY,
    ID_USER INT NOT NULL,
    FECHA DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    HORA_ENTRADA DATETIME NOT NULL,
    HORA_SALIDA DATETIME,
    HOURS_WORKED DECIMAL(4, 2) CHECK (
        HOURS_WORKED >= 0
        AND HOURS_WORKED <= 24
    ),
    HOURLY_RATE DECIMAL(10, 2) NOT NULL CHECK (HOURLY_RATE >= 0),
    PLANNED_HOURS DECIMAL(4, 2) NOT NULL CHECK (PLANNED_HOURS > 0),
    STATE TINYINT(1) NOT NULL DEFAULT 1 CHECK (STATE IN (0, 1, 2)),
    CONSTRAINT FK_LOGS_USER FOREIGN KEY (ID_USER) REFERENCES USERS (ID_USER),
    CONSTRAINT CHK_VALID_HOURS CHECK (
        HORA_SALIDA IS NULL
        OR HORA_SALIDA >= HORA_ENTRADA
    )
) ENGINE = InnoDB;

-- 13. PRESENTATIONS
CREATE TABLE PRESENTATIONS (
    ID_PRESENTATION INT AUTO_INCREMENT PRIMARY KEY,
    ID_PRODUCT INT NOT NULL,
    NAME VARCHAR(50) NOT NULL,
    DESCRIPTION TEXT,
    COST DECIMAL(10, 2) NOT NULL DEFAULT 0 CHECK (COST >= 0),
    PRICE DECIMAL(10, 2) NOT NULL CHECK (PRICE >= 0),
    DELIVERY_PRICE DECIMAL(10, 2) CHECK (DELIVERY_PRICE >= 0),
    TAKEOUT_PRICE DECIMAL(10, 2) CHECK (TAKEOUT_PRICE >= 0),
    PROMO_PRICE DECIMAL(10, 2) CHECK (PROMO_PRICE >= 0),
    PREPARATION_TIME INT NOT NULL DEFAULT 0 CHECK (
        PREPARATION_TIME >= 0
        AND PREPARATION_TIME <= 180
    ),
    DISH_PHOTO_URL VARCHAR(500),
    STATE TINYINT(1) NOT NULL DEFAULT 1 CHECK (STATE IN (0, 1)),
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PRESENTATIONS_PRODUCT FOREIGN KEY (ID_PRODUCT) REFERENCES PRODUCTS (ID_PRODUCT),
    CONSTRAINT CHK_PRESENTATIONS_NAME CHECK (CHAR_LENGTH(TRIM(NAME)) >= 2),
    CONSTRAINT CHK_PRESENTATIONS_PRICE CHECK (PRICE >= COST)
) ENGINE = InnoDB;

-- 14. PURCHASE_ORDERS
CREATE TABLE PURCHASE_ORDERS (
    ID_PURCHASE_ORDER INT AUTO_INCREMENT PRIMARY KEY,
    ORDER_NUMBER VARCHAR(50) NOT NULL UNIQUE,
    ID_SUPPLIER INT NOT NULL,
    ID_USER INT NOT NULL,
    ORDER_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DELIVERY_DATE DATE NOT NULL,
    RECEIVED_DATE DATETIME,
    TOTAL DECIMAL(12, 2) NOT NULL CHECK (TOTAL >= 0),
    ORDER_STATUS ENUM(
        'PENDIENTE',
        'CONFIRMADO',
        'EN_TRANSITO',
        'RECIBIDO',
        'CANCELADO'
    ) NOT NULL DEFAULT 'PENDIENTE',
    PAYMENT_STATUS ENUM(
        'PENDIENTE',
        'PAGADO_PARCIAL',
        'PAGADO_COMPLETO'
    ) NOT NULL DEFAULT 'PENDIENTE',
    NOTES TEXT,
    STATE TINYINT(1) NOT NULL DEFAULT 1 CHECK (STATE IN (0, 1)),
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PO_SUPPLIER FOREIGN KEY (ID_SUPPLIER) REFERENCES SUPPLIERS (ID_SUPPLIER),
    CONSTRAINT FK_PO_USER FOREIGN KEY (ID_USER) REFERENCES USERS (ID_USER),
    CONSTRAINT CHK_PO_NUMBER CHECK (
        CHAR_LENGTH(TRIM(ORDER_NUMBER)) >= 3
    ),
    CONSTRAINT CHK_PO_DELIVERY CHECK (
        DELIVERY_DATE >= DATE(ORDER_DATE)
    ),
    CONSTRAINT CHK_PO_RECEIVED CHECK (
        RECEIVED_DATE IS NULL
        OR RECEIVED_DATE >= ORDER_DATE
    )
) ENGINE = InnoDB;

-- 15. INVENTORY_MOVEMENTS
CREATE TABLE INVENTORY_MOVEMENTS (
    ID_MOVEMENT INT AUTO_INCREMENT PRIMARY KEY,
    ID_INGREDIENT INT NOT NULL,
    MOVEMENT_TYPE ENUM(
        'ENTRADA',
        'SALIDA',
        'AJUSTE',
        'MERMA',
        'DEVOLUCION'
    ) NOT NULL,
    QUANTITY DECIMAL(10, 2) NOT NULL CHECK (QUANTITY != 0),
    PREVIOUS_STOCK DECIMAL(10, 2) NOT NULL CHECK (PREVIOUS_STOCK >= 0),
    NEW_STOCK DECIMAL(10, 2) NOT NULL CHECK (NEW_STOCK >= 0),
    UNIT_COST DECIMAL(10, 2) CHECK (UNIT_COST >= 0),
    TOTAL_COST DECIMAL(12, 2) CHECK (TOTAL_COST >= 0),
    REASON VARCHAR(255) NOT NULL,
    ID_USER INT NOT NULL,
    MOVEMENT_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    NOTES TEXT,
    CONSTRAINT FK_IM_INGREDIENT FOREIGN KEY (ID_INGREDIENT) REFERENCES INGREDIENTS (ID_INGREDIENT),
    CONSTRAINT FK_IM_USER FOREIGN KEY (ID_USER) REFERENCES USERS (ID_USER),
    CONSTRAINT CHK_IM_REASON CHECK (
        CHAR_LENGTH(TRIM(REASON)) >= 3
    )
) ENGINE = InnoDB;

-- 16. RESERVATIONS
CREATE TABLE RESERVATIONS (
    ID_RESERVATION INT AUTO_INCREMENT PRIMARY KEY,
    ID_CUSTOMER INT NOT NULL,
    ID_TABLE INT NOT NULL,
    RESERVATION_DATE DATETIME NOT NULL,
    NUMBER_OF_PEOPLE INT NOT NULL CHECK (
        NUMBER_OF_PEOPLE > 0
        AND NUMBER_OF_PEOPLE <= 50
    ),
    CUSTOMER_NAME VARCHAR(200) NOT NULL,
    CUSTOMER_PHONE VARCHAR(20) NOT NULL,
    SPECIAL_REQUESTS TEXT,
    RESERVATION_STATUS ENUM(
        'PENDIENTE',
        'CONFIRMADA',
        'CANCELADA',
        'COMPLETADA',
        'NO_SHOW'
    ) NOT NULL DEFAULT 'PENDIENTE',
    CREATED_BY INT NOT NULL,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    NOTES TEXT,
    CONSTRAINT FK_RES_CUSTOMER FOREIGN KEY (ID_CUSTOMER) REFERENCES CUSTOMERS (ID_CUSTOMER),
    CONSTRAINT FK_RES_TABLE FOREIGN KEY (ID_TABLE) REFERENCES TABLES (ID_TABLE),
    CONSTRAINT FK_RES_USER FOREIGN KEY (CREATED_BY) REFERENCES USERS (ID_USER),
    CONSTRAINT CHK_RES_NAME CHECK (
        CHAR_LENGTH(TRIM(CUSTOMER_NAME)) >= 3
    ),
    CONSTRAINT CHK_RES_PHONE CHECK (
        CHAR_LENGTH(TRIM(CUSTOMER_PHONE)) >= 9
    ),
    CONSTRAINT CHK_RES_DATE CHECK (
        RESERVATION_DATE >= CREATED_AT
    )
) ENGINE = InnoDB;

-- 17. QR_SESSIONS
CREATE TABLE QR_SESSIONS (
    ID_SESSION INT AUTO_INCREMENT PRIMARY KEY,
    ID_TABLE INT NOT NULL,
    ID_CUSTOMER INT,
    SESSION_TOKEN VARCHAR(100) NOT NULL UNIQUE,
    CUSTOMER_NAME VARCHAR(100), -- Para clientes anónimos o como respaldo
    NUMBER_OF_PEOPLE INT NOT NULL DEFAULT 1 CHECK (
        NUMBER_OF_PEOPLE > 0
        AND NUMBER_OF_PEOPLE <= 50
    ),
    SESSION_STATUS ENUM(
        'ACTIVA',
        'CERRADA',
        'EXPIRADA'
    ) NOT NULL DEFAULT 'ACTIVA',
    STARTED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CLOSED_AT DATETIME,
    EXPIRES_AT DATETIME,
    CONSTRAINT FK_QRS_TABLE FOREIGN KEY (ID_TABLE) REFERENCES TABLES (ID_TABLE),
    CONSTRAINT FK_QRS_CUSTOMER FOREIGN KEY (ID_CUSTOMER) REFERENCES CUSTOMERS (ID_CUSTOMER), --
    CONSTRAINT CHK_QRS_TOKEN CHECK (
        CHAR_LENGTH(TRIM(SESSION_TOKEN)) >= 10
    ),
    CONSTRAINT CHK_QRS_CLOSE CHECK (
        CLOSED_AT IS NULL
        OR CLOSED_AT >= STARTED_AT
    )
) ENGINE = InnoDB;
-- 18. ORDERS
CREATE TABLE ORDERS (
    ID_ORDER INT AUTO_INCREMENT PRIMARY KEY,
    ID_USER INT NOT NULL,
    ID_CUSTOMER INT,
    ORDER_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ORDER_STATUS ENUM(
        'PENDIENTE',
        'EN_PREPARACION',
        'LISTO',
        'ENTREGADO',
        'CERRADO',
        'CANCELADO'
    ) NOT NULL,
    TYPE_OF_CONSUMPTION ENUM(
        'LOCAL',
        'DELIVERY',
        'TAKEOUT',
        'PROMO'
    ) NOT NULL,
    ID_TABLE INT,
    TOTAL DECIMAL(10, 2) NOT NULL CHECK (TOTAL >= 0),
    TOTAL_ITEMS INT NOT NULL CHECK (
        TOTAL_ITEMS >= 0
        AND TOTAL_ITEMS <= 500
    ),
    NUMBER_OF_PEOPLE INT NOT NULL DEFAULT 1 CHECK (
        NUMBER_OF_PEOPLE > 0
        AND NUMBER_OF_PEOPLE <= 50
    ),
    DELIVERY_ADDRESS VARCHAR(255),
    CUSTOMER_NOTES TEXT,
    CONFIRMED TINYINT(1) NOT NULL DEFAULT 0 CHECK (CONFIRMED IN (0, 1)),
    CONSTRAINT FK_ORDERS_USER FOREIGN KEY (ID_USER) REFERENCES USERS (ID_USER),
    CONSTRAINT FK_ORDERS_CUSTOMER FOREIGN KEY (ID_CUSTOMER) REFERENCES CUSTOMERS (ID_CUSTOMER),
    CONSTRAINT FK_ORDERS_TABLE FOREIGN KEY (ID_TABLE) REFERENCES TABLES (ID_TABLE),
    CONSTRAINT CHK_DELIVERY_ADDRESS CHECK (
        (
            TYPE_OF_CONSUMPTION = 'DELIVERY'
            AND DELIVERY_ADDRESS IS NOT NULL
            AND CHAR_LENGTH(TRIM(DELIVERY_ADDRESS)) >= 10
        )
        OR (
            TYPE_OF_CONSUMPTION != 'DELIVERY'
        )
    ),
    CONSTRAINT CHK_TABLE_LOCAL CHECK (
        (
            TYPE_OF_CONSUMPTION = 'LOCAL'
            AND ID_TABLE IS NOT NULL
        )
        OR (
            TYPE_OF_CONSUMPTION != 'LOCAL'
        )
    )
) ENGINE = InnoDB;

