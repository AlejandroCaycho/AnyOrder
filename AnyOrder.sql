    CONSTRAINT FK_OD_ORDER FOREIGN KEY (ID_ORDER) REFERENCES ORDERS (ID_ORDER) ON DELETE CASCADE,
    CONSTRAINT FK_OD_PRESENTATION FOREIGN KEY (ID_PRESENTATION) REFERENCES PRESENTATIONS (ID_PRESENTATION)
) ENGINE = InnoDB;

