-- =======================================================
-- MIGRACIÓN A MYSQL - AnyOrder DATABASE (CORREGIDO)
-- =======================================================

-- Eliminar la base de datos si existe y crearla nuevamente
DROP DATABASE IF EXISTS AnyOrder;

CREATE DATABASE AnyOrder CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE AnyOrder;

-- =======================================================
-- NIVEL 1: TABLAS SIN DEPENDENCIAS
-- =======================================================

-- 1. AREAS
CREATE TABLE AREAS (
    ID_AREA INT AUTO_INCREMENT PRIMARY KEY,
    NAME_AREA VARCHAR(100) NOT NULL UNIQUE,
    DESCRIPTION TEXT,
    STATE TINYINT(1) NOT NULL DEFAULT 1 CHECK (STATE IN (0, 1)),
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CHK_AREAS_NAME CHECK (
        CHAR_LENGTH(TRIM(NAME_AREA)) >= 2
    )
) ENGINE = InnoDB;

-- 2. ROLES
CREATE TABLE ROLES (
    ID_ROLE INT AUTO_INCREMENT PRIMARY KEY,
    NAME_ROLE VARCHAR(255) NOT NULL UNIQUE,
    DESCRIPTION TEXT,
    ROLE_TYPE ENUM('EMPLOYEE', 'CUSTOMER') NOT NULL DEFAULT 'EMPLOYEE',
    -- Permisos específicos para clientes
    CAN_VIEW_MENU TINYINT(1) NOT NULL DEFAULT 1,
    CAN_PLACE_ORDERS TINYINT(1) NOT NULL DEFAULT 0,
    CAN_VIEW_PRICES TINYINT(1) NOT NULL DEFAULT 1,
    STATE TINYINT(1) NOT NULL DEFAULT 1 CHECK (STATE IN (0, 1)),
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CHK_ROLES_NAME CHECK (
        CHAR_LENGTH(TRIM(NAME_ROLE)) >= 2
    )
) ENGINE = InnoDB;

-- 3. PERMISSIONS
CREATE TABLE PERMISSIONS (
    ID_PERMISSION INT AUTO_INCREMENT PRIMARY KEY,
    NAME_PERMISSION VARCHAR(100) NOT NULL UNIQUE,
    DESCRIPTION TEXT,
    STATE TINYINT(1) NOT NULL DEFAULT 1 CHECK (STATE IN (0, 1)),
    CONSTRAINT CHK_PERMISSIONS_NAME CHECK (
        CHAR_LENGTH(TRIM(NAME_PERMISSION)) >= 3
    )
) ENGINE = InnoDB;

-- 4. SUPPLIERS
CREATE TABLE SUPPLIERS (
    ID_SUPPLIER INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(150) NOT NULL,
    CONTACT_NAME VARCHAR(100) NOT NULL,
    PHONE VARCHAR(20) NOT NULL,
    EMAIL VARCHAR(150),
    ADDRESS VARCHAR(255) NOT NULL,
    DOCUMENT_TYPE ENUM('RUC', 'DNI', 'CEX') NOT NULL,
    DOCUMENT_NUMBER VARCHAR(20) NOT NULL UNIQUE,
    PAYMENT_TERMS VARCHAR(100),
    NOTES TEXT,
    STATE TINYINT(1) NOT NULL DEFAULT 1 CHECK (STATE IN (0, 1)),
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CHK_SUPPLIERS_NAME CHECK (CHAR_LENGTH(TRIM(NAME)) >= 3),
    CONSTRAINT CHK_SUPPLIERS_CONTACT CHECK (
        CHAR_LENGTH(TRIM(CONTACT_NAME)) >= 3
    ),
    CONSTRAINT CHK_SUPPLIERS_PHONE CHECK (CHAR_LENGTH(TRIM(PHONE)) >= 9),
    CONSTRAINT CHK_SUPPLIERS_EMAIL CHECK (
        EMAIL IS NULL
        OR EMAIL REGEXP '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$'
    ),
    CONSTRAINT CHK_SUPPLIERS_DOCUMENT CHECK (
        CHAR_LENGTH(TRIM(DOCUMENT_NUMBER)) >= 8
    )
) ENGINE = InnoDB;

-- 5. CATEGORIES
CREATE TABLE CATEGORIES (
    ID_CATEGORY INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(50) NOT NULL UNIQUE,
    DESCRIPTION TEXT,
    SECTION VARCHAR(100) NOT NULL,
    DELIVERY TINYINT(1) NOT NULL DEFAULT 0 CHECK (DELIVERY IN (0, 1)),
    DISPLAY_ORDER INT NOT NULL DEFAULT 0 CHECK (DISPLAY_ORDER >= 0),
    STATE TINYINT(1) NOT NULL DEFAULT 1 CHECK (STATE IN (0, 1)),
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CHK_CATEGORIES_NAME CHECK (CHAR_LENGTH(TRIM(NAME)) >= 2),
    CONSTRAINT CHK_CATEGORIES_SECTION CHECK (
        CHAR_LENGTH(TRIM(SECTION)) >= 2
    )
) ENGINE = InnoDB;

-- =======================================================
-- NIVEL 2: TABLAS QUE DEPENDEN DEL NIVEL 1
-- =======================================================

-- 6. ROLE_PERMISSIONS
CREATE TABLE ROLE_PERMISSIONS (
    ID_ROLE INT NOT NULL,
    ID_PERMISSION INT NOT NULL,
    PRIMARY KEY (ID_ROLE, ID_PERMISSION),
    CONSTRAINT FK_RP_ROLE FOREIGN KEY (ID_ROLE) REFERENCES ROLES (ID_ROLE) ON DELETE CASCADE,
    CONSTRAINT FK_RP_PERMISSION FOREIGN KEY (ID_PERMISSION) REFERENCES PERMISSIONS (ID_PERMISSION) ON DELETE CASCADE
) ENGINE = InnoDB;

-- 7. USERS
CREATE TABLE USERS (
    ID_USER INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    SURNAMES VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(255) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    DOCUMENT_NUMBER VARCHAR(20) NOT NULL UNIQUE,
    DOCUMENT_TYPE ENUM('DNI', 'CEX', 'PAS', 'RUC') NOT NULL,
    GENDER ENUM('M', 'F', 'O') DEFAULT NULL,
    PHONE VARCHAR(20) NOT NULL,
    ADRESS VARCHAR(255) NOT NULL,
    PROFILE_PHOTO VARCHAR(255),
    REGISTRATION_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    STATE TINYINT(1) NOT NULL DEFAULT 1 CHECK (STATE IN (0, 1)),
    ID_ROLE INT NOT NULL,
    ID_AREA INT NOT NULL,
    HORA_INICIO TIME NOT NULL,
    HORA_FIN TIME NOT NULL,
    PLANNED_HOURS DECIMAL(4, 2) NOT NULL CHECK (
        PLANNED_HOURS > 0
        AND PLANNED_HOURS <= 24
    ),
    TURNO VARCHAR(50) NOT NULL,
    HOURLY_RATE DECIMAL(10, 2) NOT NULL DEFAULT 0.00 CHECK (HOURLY_RATE >= 0),
    CONSTRAINT FK_USERS_AREA FOREIGN KEY (ID_AREA) REFERENCES AREAS (ID_AREA),
    CONSTRAINT FK_USERS_ROLE FOREIGN KEY (ID_ROLE) REFERENCES ROLES (ID_ROLE),
    CONSTRAINT CHK_USERS_NAME CHECK (CHAR_LENGTH(TRIM(NAME)) >= 2),
    CONSTRAINT CHK_USERS_SURNAMES CHECK (
        CHAR_LENGTH(TRIM(SURNAMES)) >= 2
    ),
    CONSTRAINT CHK_USERS_EMAIL CHECK (
        EMAIL REGEXP '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$'
    ),
    CONSTRAINT CHK_USERS_PASSWORD CHECK (CHAR_LENGTH(PASSWORD) >= 6),
    CONSTRAINT CHK_USERS_DOCUMENT CHECK (
        CHAR_LENGTH(TRIM(DOCUMENT_NUMBER)) >= 8
    ),
    CONSTRAINT CHK_USERS_PHONE CHECK (CHAR_LENGTH(TRIM(PHONE)) >= 9),
    CONSTRAINT CHK_USERS_TURNO CHECK (CHAR_LENGTH(TRIM(TURNO)) >= 3),
    CONSTRAINT CHK_USERS_HOURS CHECK (HORA_FIN > HORA_INICIO)
) ENGINE = InnoDB;

-- 8. CUSTOMERS
CREATE TABLE CUSTOMERS (
    ID_CUSTOMER INT AUTO_INCREMENT PRIMARY KEY,
    FIRST_NAME VARCHAR(100) NOT NULL,
    LAST_NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(150),
    PASSWORD VARCHAR(255),
    PHONE VARCHAR(20) NOT NULL,
    DOCUMENT_TYPE ENUM('DNI', 'CEX', 'PAS', 'RUC') NOT NULL,
    DOCUMENT_NUMBER VARCHAR(20) NOT NULL UNIQUE,
    ADDRESS VARCHAR(255),
    CUSTOMER_TYPE ENUM('NATURAL', 'JURIDICO') NOT NULL DEFAULT 'NATURAL',
    ID_ROLE INT NOT NULL,
    LAST_PURCHASE_DATE DATETIME,
    TOTAL_PURCHASES INT NOT NULL DEFAULT 0 CHECK (TOTAL_PURCHASES >= 0),
    TOTAL_SPENT DECIMAL(12, 2) NOT NULL DEFAULT 0 CHECK (TOTAL_SPENT >= 0),
    STATE TINYINT(1) NOT NULL DEFAULT 1 CHECK (STATE IN (0, 1)),
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_CUSTOMERS_ROLE FOREIGN KEY (ID_ROLE) REFERENCES ROLES (ID_ROLE),
    CONSTRAINT CHK_CUSTOMERS_FNAME CHECK (
        CHAR_LENGTH(TRIM(FIRST_NAME)) >= 2
    ),
    CONSTRAINT CHK_CUSTOMERS_LNAME CHECK (
        CHAR_LENGTH(TRIM(LAST_NAME)) >= 2
    ),
    CONSTRAINT CHK_CUSTOMERS_PHONE CHECK (CHAR_LENGTH(TRIM(PHONE)) >= 9),
    CONSTRAINT CHK_CUSTOMERS_DOCUMENT CHECK (
        CHAR_LENGTH(TRIM(DOCUMENT_NUMBER)) >= 8
    )
) ENGINE = InnoDB;

-- 9. PRODUCTS
CREATE TABLE PRODUCTS (
    ID_PRODUCT INT AUTO_INCREMENT PRIMARY KEY,
    ID_CATEGORY INT NOT NULL,
    NAME VARCHAR(100) NOT NULL,
    DESCRIPTION TEXT,
    ID_AREA INT NOT NULL,
    STATE TINYINT(1) NOT NULL DEFAULT 1 CHECK (STATE IN (0, 1)),
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UQ_PRODUCT_NAME_CAT UNIQUE (ID_CATEGORY, NAME),
    CONSTRAINT FK_PRODUCTS_CATEGORY FOREIGN KEY (ID_CATEGORY) REFERENCES CATEGORIES (ID_CATEGORY),
    CONSTRAINT FK_PRODUCTS_AREA FOREIGN KEY (ID_AREA) REFERENCES AREAS (ID_AREA),
    CONSTRAINT CHK_PRODUCTS_NAME CHECK (CHAR_LENGTH(TRIM(NAME)) >= 2)
) ENGINE = InnoDB;

-- 10. INGREDIENTS
CREATE TABLE INGREDIENTS (
    ID_INGREDIENT INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    CODE VARCHAR(50) NOT NULL UNIQUE,
    CATEGORY VARCHAR(50) NOT NULL,
    UNIT VARCHAR(20) NOT NULL,
    QUANTITY DECIMAL(10, 2) NOT NULL DEFAULT 0 CHECK (QUANTITY >= 0),
    MIN_STOCK DECIMAL(10, 2) NOT NULL DEFAULT 0 CHECK (MIN_STOCK >= 0),
    UNIT_PRICE DECIMAL(10, 2) NOT NULL DEFAULT 0 CHECK (UNIT_PRICE >= 0),
    ID_SUPPLIER INT NOT NULL,
    EXPIRATION_DATE DATE,
    DESCRIPTION TEXT,
    STATE TINYINT(1) NOT NULL DEFAULT 1 CHECK (STATE IN (0, 1)),
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_INGREDIENTS_SUPPLIER FOREIGN KEY (ID_SUPPLIER) REFERENCES SUPPLIERS (ID_SUPPLIER),
    CONSTRAINT CHK_INGREDIENTS_NAME CHECK (CHAR_LENGTH(TRIM(NAME)) >= 2),
    CONSTRAINT CHK_INGREDIENTS_CODE CHECK (CHAR_LENGTH(TRIM(CODE)) >= 2),
    CONSTRAINT CHK_INGREDIENTS_CATEGORY CHECK (
        CHAR_LENGTH(TRIM(CATEGORY)) >= 2
    ),
    CONSTRAINT CHK_INGREDIENTS_UNIT CHECK (CHAR_LENGTH(TRIM(UNIT)) >= 1)
) ENGINE = InnoDB;

-- 11. TABLES
CREATE TABLE TABLES (
    ID_TABLE INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(50) NOT NULL UNIQUE,
    ID_AREA INT NOT NULL,
    CAPACITY INT NOT NULL CHECK (
        CAPACITY > 0
        AND CAPACITY <= 50
    ),
    CURRENT_OCCUPANCY INT NOT NULL DEFAULT 0 CHECK (CURRENT_OCCUPANCY >= 0),
    LOCATION VARCHAR(50) NOT NULL,
    QR_CODE VARCHAR(255) UNIQUE,
    QR_TOKEN VARCHAR(100) UNIQUE,
    STATE TINYINT(1) NOT NULL DEFAULT 1 CHECK (STATE IN (0, 1)),
    IS_OCCUPIED TINYINT(1) NOT NULL DEFAULT 0 CHECK (IS_OCCUPIED IN (0, 1)),
    OCCUPIED_SINCE DATETIME,
    CONSTRAINT CHK_OCCUPANCY CHECK (CURRENT_OCCUPANCY <= CAPACITY),
    CONSTRAINT CHK_TABLES_NAME CHECK (CHAR_LENGTH(TRIM(NAME)) >= 2),
    CONSTRAINT CHK_TABLES_LOCATION CHECK (
        CHAR_LENGTH(TRIM(LOCATION)) >= 2
    ),
    CONSTRAINT FK_TABLES_AREA FOREIGN KEY (ID_AREA) REFERENCES AREAS (ID_AREA) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE = InnoDB;

