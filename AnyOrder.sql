-- Vistas para tableros y alertas del negocio
CREATE OR REPLACE VIEW VW_INVENTORY_ALERTS AS
SELECT
    I.ID_INGREDIENT,
    I.NAME,
    I.CODE,
    I.CATEGORY,
    I.UNIT,
    I.QUANTITY,
    I.MIN_STOCK,
    I.EXPIRATION_DATE,
    CASE
        WHEN I.EXPIRATION_DATE IS NOT NULL AND I.EXPIRATION_DATE < CURRENT_DATE THEN 'VENCIDO'
        WHEN I.EXPIRATION_DATE IS NOT NULL AND I.EXPIRATION_DATE <= DATE_ADD(CURRENT_DATE, INTERVAL 7 DAY) THEN 'POR_VENCER'
        WHEN I.QUANTITY <= I.MIN_STOCK THEN 'STOCK_BAJO'
        ELSE 'OK'
    END AS ALERT_TYPE
FROM INGREDIENTS I
WHERE I.STATE = 1
  AND (
      I.QUANTITY <= I.MIN_STOCK
      OR (I.EXPIRATION_DATE IS NOT NULL AND I.EXPIRATION_DATE <= DATE_ADD(CURRENT_DATE, INTERVAL 7 DAY))
  );

CREATE OR REPLACE VIEW VW_TABLES_REAL_TIME AS
SELECT
    T.ID_TABLE,
    T.NAME,
    A.NAME_AREA,
    T.CAPACITY,
    T.CURRENT_OCCUPANCY,
    T.IS_OCCUPIED,
    T.OCCUPIED_SINCE,
    CASE
        WHEN T.STATE = 0 THEN 'INACTIVA'
        WHEN T.IS_OCCUPIED = 1 THEN 'OCUPADA'
        ELSE 'LIBRE'
    END AS TABLE_STATUS
FROM TABLES T
JOIN AREAS A ON A.ID_AREA = T.ID_AREA;

CREATE OR REPLACE VIEW VW_KITCHEN_QUEUE AS
SELECT
    O.ID_ORDER,
    O.ORDER_DATE,
    O.ORDER_STATUS,
    O.TYPE_OF_CONSUMPTION,
    T.NAME AS TABLE_NAME,
    A.NAME_AREA,
    O.TOTAL_ITEMS,
    O.TOTAL,
    TIMESTAMPDIFF(MINUTE, O.ORDER_DATE, CURRENT_TIMESTAMP) AS WAIT_MINUTES
FROM ORDERS O
LEFT JOIN TABLES T ON T.ID_TABLE = O.ID_TABLE
LEFT JOIN AREAS A ON A.ID_AREA = T.ID_AREA
WHERE O.ORDER_STATUS IN ('PENDIENTE', 'EN_PREPARACION', 'LISTO');

CREATE OR REPLACE VIEW VW_DAILY_SALES_SUMMARY AS
SELECT
    DATE(S.SALE_DATE) AS SALE_DAY,
    COUNT(*) AS SALES_COUNT,
    SUM(S.TOTAL) AS GROSS_TOTAL,
    SUM(CASE WHEN S.STATE = 1 THEN S.TOTAL ELSE 0 END) AS NET_TOTAL,
    SUM(CASE WHEN S.STATE = 0 THEN S.TOTAL ELSE 0 END) AS ANNULLED_TOTAL
FROM SALES S
GROUP BY DATE(S.SALE_DATE);

CREATE OR REPLACE VIEW VW_TOP_PRESENTATIONS AS
SELECT
    P.ID_PRESENTATION,
    PR.NAME AS PRODUCT_NAME,
    P.NAME AS PRESENTATION_NAME,
    SUM(DS.AMOUNT) AS UNITS_SOLD,
    SUM(DS.SUBTOTAL) AS TOTAL_SOLD
FROM DETAIL_SALE DS
JOIN SALES S ON S.ID_SALE = DS.ID_SALE AND S.STATE = 1
JOIN PRESENTATIONS P ON P.ID_PRESENTATION = DS.ID_PRESENTATION
JOIN PRODUCTS PR ON PR.ID_PRODUCT = P.ID_PRODUCT
GROUP BY P.ID_PRESENTATION, PR.NAME, P.NAME
ORDER BY UNITS_SOLD DESC, TOTAL_SOLD DESC;

